export type IconName = keyof typeof GLYPHS | 'back';

const pathCache = new Map<IconName, string>();
function glyphPath(name: IconName): string {
  const cached = pathCache.get(name);
  if (cached) return cached;
  const rows: readonly string[] =
    name === 'back' ? GLYPHS.arrow.map((row) => [...row].reverse().join('')) : GLYPHS[name];
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x += 1;
        continue;
      }
      let end = x + 1;
      while (row[end] === '#') end += 1;
      d += `M${x} ${y}h${end - x}v1h${x - end}z`;
      x = end;
    }
  });
  pathCache.set(name, d);
  return d;
}

export function Icon({
  name,
  tint = color.muted,
  size = 20,
}: Readonly<{ name: IconName; tint?: ColorValue; size?: number }>): React.JSX.Element {
  return (
    <View aria-hidden style={styles.icon}>
      <Svg width={size} height={size} viewBox="0 0 10 10">
        <Path d={glyphPath(name)} fill={tint} />
      </Svg>
    </View>
  );
}

const styles = StyleSheet.create({ icon: { flexShrink: 0 } });
