#!/usr/bin/env node
/**
 * bruhs-theme-swift — writes the bruhs tokens as a Swift file for native Mac apps: every colour
 * in Display P3, the semantic roles (src/lib/semantic.ts) as appearance-aware colours, and
 * the radius and motion tokens.
 *
 *   bruhs-theme-swift <output.swift>          write the file
 *   bruhs-theme-swift <output.swift> --check  fail if the file differs from the tokens
 */
import { readFileSync, writeFileSync } from "node:fs";
import { parseColorTokens, toRgb } from "../src/lib/oklch.ts";
import { semanticColors } from "../src/lib/semantic.ts";

const [output, flag] = process.argv.slice(2);
if (!output || (flag && flag !== "--check")) {
  console.error("usage: bruhs-theme-swift <output.swift> [--check]");
  process.exit(2);
}

const css = readFileSync(new URL("../src/styles/index.css", import.meta.url), "utf8");
const colors = parseColorTokens(css);
const swiftName = (token) => token.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase());
const n = (v) => v.toFixed(5);

function token(name) {
  const value = css.match(new RegExp(`--${name}:\\s*([^;]+);`))?.[1].trim();
  if (!value) throw new Error(`--${name} is missing from packages/ui/src/styles/index.css.`);
  return value;
}
const points = (rem) => Number.parseFloat(rem) * 16;
const seconds = (ms) => Number.parseFloat(ms) / 1000;
function bezier(name) {
  const parts = token(name).match(/cubic-bezier\(([^)]+)\)/)?.[1].split(",").map((v) => Number(v.trim()));
  if (!parts || parts.length !== 4) throw new Error(`--${name} is not a cubic-bezier().`);
  return parts;
}

function ref(r) {
  if (typeof r === "string") {
    if (!colors.has(r)) throw new Error(`Semantic role names --color-${r}, which doesn't exist.`);
    return `BruhsPalette.${swiftName(r)}`;
  }
  if (!colors.has(r.token)) throw new Error(`Semantic role names --color-${r.token}, which doesn't exist.`);
  return `BruhsPalette.${swiftName(r.token)}.withAlphaComponent(${r.alpha})`;
}

const palette = [...colors].map(([name, color]) => {
  const [r, g, b] = toRgb(color, "p3");
  return `    static let ${swiftName(name)} = NSColor(displayP3Red: ${n(r)}, green: ${n(g)}, blue: ${n(b)}, alpha: 1)`;
});

const roles = Object.entries(semanticColors).map(([role, spec]) => {
  const args = [`dark: ${ref(spec.dark)}`, `light: ${ref(spec.light)}`];
  if ("darkHighContrast" in spec) args.push(`darkHighContrast: ${ref(spec.darkHighContrast)}`);
  if ("lightHighContrast" in spec) args.push(`lightHighContrast: ${ref(spec.lightHighContrast)}`);
  return `    static let ${role} = appearanceColor(${args.join(", ")})`;
});
const colorRoles = Object.keys(semanticColors).map((role) => `    static let ${role} = Color(nsColor: BruhsNSColor.${role})`);

const radii = ["seed", "grape", "lychee", "mango", "pomelo"].map((r) => `    static let ${r}: CGFloat = ${points(token(`radius-${r}`))}`);
const durations = ["blink", "fast", "standard", "slow", "bloom"].map((d) => `    static let ${d}: Double = ${seconds(token(`duration-${d}`))}`);
const curves = ["standard", "entrance", "exit"].map((e) => {
  const [x1, y1, x2, y2] = bezier(`ease-${e}`);
  return `    static func ${e}(duration: Double) -> Animation { .timingCurve(${x1}, ${y1}, ${x2}, ${y2}, duration: duration) }`;
});

const swift = `// Generated by bruhs-theme-swift from packages/ui (styles/index.css, src/lib/semantic.ts).
// Change the theme and regenerate; \`bruhs-theme-swift --check\` fails while this file is stale.
import AppKit
import SwiftUI

/// Every bruhs colour token, in Display P3.
enum BruhsPalette {
${palette.join("\n")}
}

/// Semantic roles for AppKit: window backgrounds, table drawing. They follow the system appearance and
/// Increase Contrast.
enum BruhsNSColor {
${roles.join("\n")}
}

/// The same roles for SwiftUI.
enum BruhsColor {
${colorRoles.join("\n")}
}

enum BruhsRadius {
${radii.join("\n")}
}

/// Durations in seconds and the bruhs easing curves. Live data never animates.
enum BruhsMotion {
${durations.join("\n")}
${curves.join("\n")}
}

private func appearanceColor(dark: NSColor, light: NSColor, darkHighContrast: NSColor? = nil, lightHighContrast: NSColor? = nil) -> NSColor {
    NSColor(name: nil) { appearance in
        switch appearance.bestMatch(from: [.aqua, .darkAqua, .accessibilityHighContrastAqua, .accessibilityHighContrastDarkAqua]) {
        case .accessibilityHighContrastDarkAqua?: darkHighContrast ?? dark
        case .accessibilityHighContrastAqua?: lightHighContrast ?? light
        case .darkAqua?: dark
        default: light
        }
    }
}
`;

if (flag === "--check") {
  let current = null;
  try { current = readFileSync(output, "utf8"); } catch {}
  if (current !== swift) {
    console.error(`${output} is out of date with the bruhs tokens. Run \`node packages/ui/scripts/swift-tokens.mjs ${output}\` and commit it.`);
    process.exit(1);
  }
  console.log(`bruhs-theme-swift: ${output} matches the tokens`);
} else {
  writeFileSync(output, swift);
  console.log(`bruhs-theme-swift: wrote ${colors.size} colours and ${roles.length} roles to ${output}`);
}
